#!/usr/bin/env python3
"""Writes the menus' fonts' letter advances as a Rust table, for the Halo UI
plugin to measure its lines with (engine/crates/halo_ui/src/advances.rs):

    python tools/font_advances.py           # writes the table
    python tools/font_advances.py --check   # fails when it is stale

The app sets each letter at its font's own advance (MenuPass.swift's
CTFontGetAdvancesForGlyphs, with no kerning), so a line's width is the sum of
its letters' advances from the font's hmtx table, here kept in the font's own
units for each printable ASCII character. The fonts are read with a small
bounds-checked reader of the few tables needed (head, hhea, hmtx and cmap's
format 4); a font that does not parse fails the run.
"""

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "port/assets/fonts"
OUTPUT = ROOT / "engine/crates/halo_ui/src/advances.rs"

# the Face each font is set for (MenuPass.swift)
FACES = [
    ("TITLE", "OpenCE-Regular.ttf", "Face::Title"),
    ("HEAVY", "Overpass-900.ttf", "Face::Heavy"),
    ("BOLD", "Overpass-750.ttf", "Face::Bold and Face::Semibold"),
]
FIRST, LAST = 0x20, 0x7E


class Font:
    """The tables of a TrueType font, each read only within the file."""

    def __init__(self, data: bytes):
        self.data = data
        count = self.unpack(">H", 4)[0]
        self.tables = {}
        for index in range(count):
            tag, _, offset, length = self.unpack(">4sIII", 12 + 16 * index)
            if offset + length > len(data):
                raise ValueError(f"table {tag!r} runs past the file")
            self.tables[tag.decode("latin-1")] = (offset, length)

    def unpack(self, form: str, at: int):
        size = struct.calcsize(form)
        if at < 0 or at + size > len(self.data):
            raise ValueError(f"read at {at} runs past the file")
        return struct.unpack_from(form, self.data, at)

    def table(self, tag: str) -> int:
        if tag not in self.tables:
            raise ValueError(f"no {tag} table")
        return self.tables[tag][0]

    def units_per_em(self) -> int:
        return self.unpack(">H", self.table("head") + 18)[0]

    def advance(self, glyph: int) -> int:
        metrics = self.unpack(">H", self.table("hhea") + 34)[0]
        if metrics == 0:
            raise ValueError("no horizontal metrics")
        # (glyphs past the last metric share its advance)
        return self.unpack(">H", self.table("hmtx") + 4 * min(glyph, metrics - 1))[0]

    def glyph(self, code: int) -> int:
        cmap = self.table("cmap")
        count = self.unpack(">H", cmap + 2)[0]
        for index in range(count):
            platform, encoding, offset = self.unpack(">HHI", cmap + 4 + 8 * index)
            if (platform, encoding) in ((3, 1), (0, 3)) and self.unpack(">H", cmap + offset)[0] == 4:
                return self.format4(cmap + offset, code)
        raise ValueError("no Unicode cmap of format 4")

    def format4(self, at: int, code: int) -> int:
        segments = self.unpack(">H", at + 6)[0] // 2
        ends = at + 14
        starts = ends + 2 * segments + 2
        deltas = starts + 2 * segments
        ranges = deltas + 2 * segments
        for segment in range(segments):
            end = self.unpack(">H", ends + 2 * segment)[0]
            if code > end:
                continue
            start = self.unpack(">H", starts + 2 * segment)[0]
            if code < start:
                return 0
            delta = self.unpack(">h", deltas + 2 * segment)[0]
            place = ranges + 2 * segment
            offset = self.unpack(">H", place)[0]
            if offset == 0:
                return (code + delta) & 0xFFFF
            glyph = self.unpack(">H", place + offset + 2 * (code - start))[0]
            return (glyph + delta) & 0xFFFF if glyph else 0
        return 0


def table() -> str:
    lines = [
        "//! Generated by tools/font_advances.py from port/assets/fonts; do not edit.",
        "//! Each printable ASCII character's advance (from a space, 0x20, to a",
        "//! tilde, 0x7E), in its font's own units, as the app sets it.",
        "",
        "/// A font's advances, in units of which `em` make the font's size.",
        "pub(crate) struct Advances {",
        "    /// The units in the em (head's unitsPerEm).",
        "    pub(crate) em: f32,",
        f"    /// Each character's advance, from 0x{FIRST:02X} to 0x{LAST:02X}.",
        f"    pub(crate) units: [u16; {LAST - FIRST + 1}],",
        "}",
    ]
    for name, file, face in FACES:
        font = Font((FONTS / file).read_bytes())
        units = [font.advance(font.glyph(code)) for code in range(FIRST, LAST + 1)]
        lines.append("")
        lines.append(f"/// {file}'s advances ({face}).")
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub(crate) const {name}: Advances = Advances {{")
        lines.append(f"    em: {font.units_per_em()}.0,")
        lines.append("    units: [")
        for row in range(0, len(units), 12):
            lines.append("        " + " ".join(f"{value}," for value in units[row : row + 12]))
        lines.append("    ],")
        lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = table()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: run python tools/font_advances.py")
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
